// ============================================================
// 规则摘要：每次决策都放在 user 消息开头
// 与引擎实现的流程严格一致（叫价→提案→应答→成交倒计时→结算）；按本局变体拼装。
// 改规则（src/engine）时同步这里；数字来自参数，不要写死。
// ============================================================

export interface RulesSummaryOptions {
  /** 本局变体名 */
  variantName: string
  /** 景气牌张数 = 成交笔数上限 */
  deals: number
  /** 末张股价 */
  maxShare: number
  /** 牌堆是否含稀有牌（利好 / 利空 / 独家协议） */
  rareCards: boolean
  /** 版图上出现的特殊格种类（中文名 → 效果） */
  specialSpaces: Array<{ name: string; effect: string }>
  /** 桌规是否开启（互换 / 买牌 / 兑换 / 病假牌） */
  houseRules: boolean
  /** 桌规牌堆里的病假牌张数 */
  sickCards: number
}

export function buildRulesSummary(o: RulesSummaryOptions): string {
  const endFrom = Math.max(1, o.deals - 5)
  const rare = o.rareCards ? `
  稀有牌（本局牌堆含）：利好牌——Boss打出，本笔股价 +$2M/份（已有方案的分成不变，多出的全归Boss）；利空牌——非Boss打出，本笔股价 −$1M/份（最低$1M/份，砍的是Boss净得，倒计时中也能打）；独家协议——Boss打出，本笔交易锁定：老板牌/旅行牌/利空牌都不能再打（招募仍可）。三种同样进反应窗口、可被阻止牌取消。` : ''
  const special = o.specialSpaces.length ? `
【特殊格】${o.specialSpaces.map(s => `${s.name}格：${s.effect}`).join('；')}。` : ''
  const house = o.houseRules ? `
【桌规（本局开启）】以下换牌都不结束你的行动，做完还能接着出牌 / 喊话，但每回合各限一次：
  换牌：你持有某家族的投资者时，手里该家族的成员牌可换成同家族的旅行牌（也可反着换）——自家人多余的成员卡变成打飞别人同家族代表的机票，或在自家投资者被打飞时换回成员卡补位。
  买牌：自己回合开单前，付 1 / 3 / 6 份当前股价给银行，多抽 1 / 2 / 3 张（不得超过手牌上限 12 张；钱不会回来）。
  兑换：交出两张不同种类的牌 + 付一份股价给银行，换 2 张招募牌（不可逆）——凑招募三连 / 猎头两张 / 夺回权一张的捷径。
  病假牌（牌堆含 ${o.sickCards} 张）：指定一名玩家，本回合内他不能主动出牌（家族 / 旅行 / 招募 / 老板 / 稀有牌与换牌都不行），只能被动打阻止牌；开单前、谈判中、倒计时里都能打，进反应窗口、可被阻止牌取消。` : ''
  return `
这是桌游《I'm the Boss!》的一局（${o.variantName}）：一桌人围着一张牌桌做交易，游戏结束时现金最多的人赢。
【回合】发起当前格交易；或掷骰移动后再决定交易 / 抽3张牌结束回合。手牌上限12张。
【交易需求】每格由若干需求组构成：「全部必需」组每个家族都要有代表；「N选M」组从列出的家族里凑够M个。
  代表来源：投资者牌（长期持有，可被招募夺走）或家族成员卡（手牌打出、只在本笔交易有效；被选用成交后弃掉，未用则收回手牌）。
【分成】成交时银行把全款付给Boss，Boss再按方案付给被选用代表的持有者。Boss自己的代表免费。
  一份"分红"= 总额 ÷ (投资者数+1)，是常见的心理价；同家族有多方代表时Boss只选其一，通常选要价最低者，落选者一分钱拿不到。
【谈判流程】Boss开单后先是叫价轮：从Boss左手边起轮流「喊话报价 / 出牌 / 跳过」，Boss在第一轮末位行动；之后继续轮转，Boss轮到时可提案。
  报价即承诺：你公开报出的出借价（每个代表）对本笔交易有效——Boss的方案付到这个价，你自动视为同意，不再询问你；付不到才会问你「同意/拒绝(可反报价)」。
  报价按家族分开记：你可以给唯一代表的家族报高价、给有竞争者的家族报低价；方案用了你哪几个代表就按各自的价相加。
  同意一个方案也会把该金额记为你的承诺价；拒绝时的反报价就是新的承诺价。
  全员同意后Boss可「宣布成交」→ 进入最后出牌窗口（其他人依次可打旅行/招募/老板牌等，或放行）→ 全员放行即结算。
  每任Boss最多提5次方案；方案中的代表被打飞/易主时方案作废，回合回到Boss。连续两轮全员跳过则流局；桌上凑不齐需求（缺代表）时只要全员跳过一轮就立即流局，不必再等。Boss也可以随时放弃交易（流局，大家都拿不到钱）。
【影响牌】旅行牌：让指定投资者/家族成员本笔交易失效（定向旅行只能打同家族，万能旅行任意）。
  招募：通常3张一起打出，永久夺取一个投资者（有公共区投资者时必须先招公共区）。
  夺回权：谁的最后一位常驻投资者被招募夺走，谁就获得夺回权——只需1张招募牌即可把该家族的投资者抢回来（无论此刻在谁手里，不受"先招公共区"限制）；重新拥有任何投资者后失效。
  老板牌：夺走Boss身份接管谈判（原方案作废）。以上几种打出后立即进入反应窗口，持有阻止牌的人可取消其效果。
  阻止牌不能取消另一张阻止牌，也不能取消家族成员卡。${rare}${special}${house}
【终局】股价从$2M/份逐步升到$${o.maxShare}M/份。第${endFrom}笔成交起，每次成交后Boss掷骰，命中景气牌背面数字则游戏结束；第${o.deals}笔成交后必定结束。
  领先者希望交易尽快成交（掷骰可能直接赢）；落后者应阻止领先者的交易、争取自己当Boss的大单。
`
}
